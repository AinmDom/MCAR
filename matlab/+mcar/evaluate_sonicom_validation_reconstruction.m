function write_json(path, value)
text = jsonencode(value, 'PrettyPrint', true);
file = fopen(path, 'w');
assert(file ~= -1, 'Could not open JSON output: %s', path);
cleanup = onCleanup(@() fclose(file));
fprintf(file, '%s\n', text);
clear cleanup;
end
