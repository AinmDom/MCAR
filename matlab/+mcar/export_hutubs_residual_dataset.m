function export_hutubs_residual_dataset(subjectIds, sparseOrders, ...
        numWorkers, outputName, includeStrictIldMetadata)
%EXPORT_HUTUBS_RESIDUAL_DATASET Export MCA residual-learning HDF5 files.
%
% Pilot defaults:
%   subjectIds   = 91
%   sparseOrders = 3
%   numWorkers   = 1
%   outputName   = 'pilot_pp91_n03'
%   includeStrictIldMetadata = false
%
% Each subject/order is written atomically to an independent HDF5 file.
% Python sees spectral tensors with layout [ear, direction, frequency].

if nargin < 1 || isempty(subjectIds)
    subjectIds = 91;
end
if nargin < 2 || isempty(sparseOrders)
    sparseOrders = 3;
end
if nargin < 3 || isempty(numWorkers)
    numWorkers = 1;
end
if nargin < 4 || isempty(outputName)
    outputName = 'pilot_pp91_n03';
end
if nargin < 5 || isempty(includeStrictIldMetadata)
    includeStrictIldMetadata = false;
end

subjectIds = unique(subjectIds(:).', 'stable');
sparseOrders = unique(sparseOrders(:).', 'stable');
validateattributes(subjectIds, {'numeric'}, ...
    {'integer', '>=', 1, '<=', 96, 'nonempty'});
validateattributes(sparseOrders, {'numeric'}, ...
    {'integer', '>=', 1, '<=', 10, 'nonempty'});
validateattributes(numWorkers, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1});
validateattributes(outputName, {'char', 'string'}, {'scalartext'});
validateattributes(includeStrictIldMetadata, {'logical', 'numeric'}, ...
    {'scalar'});
outputName = char(outputName);
includeStrictIldMetadata = logical(includeStrictIldMetadata);

scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
supdeqDir = fullfile(projectRoot, 'external', 'SUpDEq');
hutubsDir = fullfile(projectRoot, 'data', 'HRTF', 'hutubs');
splitFile = fullfile(projectRoot, 'configs', 'data', 'subject_split_v1.csv');
outputRoot = fullfile(projectRoot, 'data', 'processed', outputName);
subjectsRoot = fullfile(outputRoot, 'subjects');

assert(isfolder(supdeqDir), 'SUpDEq directory not found: %s', supdeqDir);
assert(isfolder(hutubsDir), 'HUTUBS directory not found: %s', hutubsDir);
assert(isfile(splitFile), 'Subject split file not found: %s', splitFile);
if ~isfolder(subjectsRoot)
    mkdir(subjectsRoot);
end

splitTable = readtable(splitFile, 'TextType', 'string');
assert(height(splitTable) == 96 && ...
    isequal(sort(splitTable.subject_id).', 1:96), ...
    'Subject split must contain each subject ID from 1 to 96 exactly once.');
assert(sum(splitTable.split == "train") == 72, ...
    'Expected 72 training subjects.');
assert(sum(splitTable.split == "val") == 12, ...
    'Expected 12 validation subjects.');
assert(sum(splitTable.split == "test") == 12, ...
    'Expected 12 test subjects.');

configuration = struct( ...
    'subjectIds', subjectIds, ...
    'sparseOrders', sparseOrders, ...
    'numWorkers', min(numWorkers, numel(subjectIds)), ...
    'outputName', outputName, ...
    'splitFile', splitFile, ...
    'splitSeed', 20260723, ...
    'referenceLebedevOrder', 35, ...
    'denseFliegeOrder', 29, ...
    'denseDirectionCount', 900, ...
    'fftOversize', 4, ...
    'frequencyMinimumHz', 50, ...
    'frequencyMaximumHz', 20000, ...
    'magnitudeFloorDb', -200, ...
    'mcaMaximumBoostDb', inf, ...
    'mcaMinimumPhase', true, ...
    'mcaLimitBelowSpatialAliasingFrequency', true, ...
    'mcaAliasingFade', 'fadeDown', ...
    'includeStrictIldMetadata', includeStrictIldMetadata, ...
    'matlabVersion', version, ...
    'startedAt', datetime('now', 'TimeZone', 'local'));
save(fullfile(outputRoot, 'run_configuration.mat'), 'configuration');

fprintf(['Starting residual export: %d subjects, orders %s, ', ...
    'frequency range %.0f-%.0f Hz.\n'], ...
    numel(subjectIds), mat2str(sparseOrders), ...
    configuration.frequencyMinimumHz, configuration.frequencyMaximumHz);

statusCells = cell(numel(subjectIds), 1);
if isscalar(subjectIds) || numWorkers == 1
    initialize_worker(supdeqDir);
    for subjectIndex = 1:numel(subjectIds)
        statusCells{subjectIndex} = process_subject( ...
            subjectIds(subjectIndex), sparseOrders, hutubsDir, subjectsRoot, ...
            splitTable, configuration);
    end
else
    requestedWorkers = min(numWorkers, numel(subjectIds));
    pool = gcp('nocreate');
    if isempty(pool)
        pool = parpool('local', requestedWorkers);
    elseif pool.NumWorkers ~= requestedWorkers
        delete(pool);
        pool = parpool('local', requestedWorkers);
    end
    addAttachedFiles(pool, {mfilename('fullpath')});
    workerEnvironment = parallel.pool.Constant( ...
        @() initialize_worker(supdeqDir));
    parfor subjectIndex = 1:numel(subjectIds)
        workerEnvironment.Value;
        statusCells{subjectIndex} = process_subject( ...
            subjectIds(subjectIndex), sparseOrders, hutubsDir, subjectsRoot, ...
            splitTable, configuration);
    end
    delete(workerEnvironment);
end

statusTable = vertcat(statusCells{:});
writetable(statusTable, fullfile(outputRoot, 'export_status.csv'));
save(fullfile(outputRoot, 'export_status.mat'), 'statusTable');

configuration.finishedAt = datetime('now', 'TimeZone', 'local');
configuration.completedFileCount = sum(statusTable.Success);
configuration.failedFileCount = sum(~statusTable.Success);
save(fullfile(outputRoot, 'run_configuration.mat'), 'configuration');

fprintf('\nResidual export finished: %d succeeded, %d failed.\n', ...
    configuration.completedFileCount, configuration.failedFileCount);
fprintf('Output root: %s\n', outputRoot);
disp(statusTable);
end

function environment = initialize_worker(supdeqDir)
originalDir = pwd;
restoreDirectory = onCleanup(@() cd(originalDir));
cd(supdeqDir);
supdeq_start;
environment = struct('initialized', true);
clear restoreDirectory;
end

function status = process_subject(subjectId, sparseOrders, hutubsDir, ...
        subjectsRoot, splitTable, config)
subjectStart = tic;
subjectDir = fullfile(subjectsRoot, sprintf('pp%d', subjectId));
if ~isfolder(subjectDir)
    mkdir(subjectDir);
end
logFile = fullfile(subjectDir, 'export.log');
diary(logFile);
stopDiary = onCleanup(@() diary('off'));

splitRow = splitTable(splitTable.subject_id == subjectId, :);
assert(height(splitRow) == 1, ...
    'Expected exactly one split row for subject %d.', subjectId);
splitName = splitRow.split;

anthropometry = readtable(fullfile(hutubsDir, 'AntrhopometricMeasures.csv'));
[headRadius, headRadiusSource] = resolve_head_radius(anthropometry, subjectId);
sofaFile = fullfile(hutubsDir, sprintf( ...
    'pp%d_HRIRs_simulated.sofa', subjectId));
assert(isfile(sofaFile), 'Simulated SOFA file not found: %s', sofaFile);
sofa = SOFAload(sofaFile);
assert(strcmp(sofa.GLOBAL_SOFAConventions, 'SimpleFreeFieldHRIR'), ...
    'Unexpected SOFA convention: %s', sofa.GLOBAL_SOFAConventions);

sourceGridCanonical = supdeq_lebedev([], config.referenceLebedevOrder);
sofaGrid = [mod(sofa.SourcePosition(:, 1), 360), ...
    90 - sofa.SourcePosition(:, 2)];
assert(size(sofaGrid, 1) == size(sourceGridCanonical, 1), ...
    'Subject %d does not contain 1730 simulated directions.', subjectId);
azimuthError = abs(mod(sofaGrid(:, 1) - ...
    sourceGridCanonical(:, 1) + 180, 360) - 180);
colatitudeError = abs(sofaGrid(:, 2) - sourceGridCanonical(:, 2));
assert(max(azimuthError) <= 1e-8 && max(colatitudeError) <= 1e-8, ...
    'Subject %d source grid does not match Lebedev N=35.', subjectId);
sourceGrid = [sofaGrid, sourceGridCanonical(:, 3)];

referenceSfd = supdeq_sofa2sfd(sofa, config.referenceLebedevOrder, ...
    sourceGrid, config.fftOversize, 'ak');
denseGrid = supdeq_fliege(config.denseFliegeOrder);
[referenceLeft, referenceRight] = supdeq_getArbHRTF( ...
    referenceSfd, denseGrid, 'DEG', 2, 'ak');
frequencyHz = referenceSfd.f(:);
frequencyMask = frequencyHz >= config.frequencyMinimumHz & ...
    frequencyHz <= config.frequencyMaximumHz;
selectedFrequencyHz = frequencyHz(frequencyMask);
assert(~isempty(selectedFrequencyHz), 'No frequency bins selected.');
assert(size(referenceLeft, 1) == size(denseGrid, 1) && ...
    size(referenceLeft, 2) == numel(frequencyHz), ...
    'Unexpected reference HRTF dimensions.');

statusRows = cell(numel(sparseOrders), 1);
for orderIndex = 1:numel(sparseOrders)
    sparseOrder = sparseOrders(orderIndex);
    outputFile = fullfile(subjectDir, sprintf('n%02d.h5', sparseOrder));
    orderStart = tic;
    try
        if is_complete_hdf5(outputFile, config.includeStrictIldMetadata)
            fprintf('Subject %d N=%d already complete; skipping.\n', ...
                subjectId, sparseOrder);
            statusRows{orderIndex} = make_status_row( ...
                subjectId, sparseOrder, splitName, true, outputFile, ...
                NaN, NaN, NaN, NaN, "Skipped existing complete file");
            continue;
        end
        if isfile(outputFile)
            delete(outputFile);
        end

        sparseGrid = supdeq_lebedev([], sparseOrder);
        [sparseLeft, sparseRight] = supdeq_getArbHRTF( ...
            referenceSfd, sparseGrid, 'DEG', 2, 'ak');
        sparseHrtf = struct( ...
            'HRTF_L', sparseLeft, ...
            'HRTF_R', sparseRight, ...
            'f', referenceSfd.f, ...
            'fs', referenceSfd.fs, ...
            'Nmax', sparseOrder, ...
            'FFToversize', referenceSfd.FFToversize, ...
            'samplingGrid', sparseGrid);
        mca = supdeq_interpHRTF( ...
            sparseHrtf, denseGrid, 'SUpDEq', 'SH', inf, headRadius);

        [mcaLogMagnitudeDb, referenceLogMagnitudeDb, ...
            correctionLogMagnitudeDb, targetResidualDb, ...
            correctionIdentityErrorDb] = build_spectral_tensors( ...
            mca, referenceLeft, referenceRight, frequencyMask, ...
            config.magnitudeFloorDb);
        strictIld = struct();
        if config.includeStrictIldMetadata
            strictIld = build_strict_ild_metadata( ...
                mca, referenceLeft, referenceRight, frequencyMask, ...
                referenceSfd.FFToversize);
        end
        directionFeatures = build_direction_features(denseGrid);

        write_subject_hdf5( ...
            outputFile, mcaLogMagnitudeDb, referenceLogMagnitudeDb, ...
            correctionLogMagnitudeDb, targetResidualDb, ...
            directionFeatures, selectedFrequencyHz, subjectId, ...
            sparseOrder, splitName, headRadius, headRadiusSource, ...
            referenceSfd.fs, referenceSfd.FFToversize, ...
            correctionIdentityErrorDb, strictIld);

        elapsedSeconds = toc(orderStart);
        sampleCount = numel(targetResidualDb);
        residualMeanDb = mean(targetResidualDb, 'all');
        residualAbsoluteMeanDb = mean(abs(targetResidualDb), 'all');
        statusRows{orderIndex} = make_status_row( ...
            subjectId, sparseOrder, splitName, true, outputFile, ...
            elapsedSeconds, sampleCount, residualMeanDb, ...
            residualAbsoluteMeanDb, "");
        fprintf(['Subject %d N=%d exported in %.1f s; ', ...
            '%d samples, residual mean %.4f dB, |residual| %.4f dB.\n'], ...
            subjectId, sparseOrder, elapsedSeconds, sampleCount, ...
            residualMeanDb, residualAbsoluteMeanDb);
        clear mca mcaLogMagnitudeDb referenceLogMagnitudeDb ...
            correctionLogMagnitudeDb targetResidualDb;
    catch exception
        elapsedSeconds = toc(orderStart);
        statusRows{orderIndex} = make_status_row( ...
            subjectId, sparseOrder, splitName, false, outputFile, ...
            elapsedSeconds, NaN, NaN, NaN, string(exception.message));
        write_failure_report( ...
            subjectId, sparseOrder, exception, subjectDir);
        fprintf(2, 'Subject %d N=%d failed: %s\n', ...
            subjectId, sparseOrder, exception.message);
    end
end
status = vertcat(statusRows{:});
fprintf('Subject %d finished in %.1f seconds.\n', ...
    subjectId, toc(subjectStart));
clear stopDiary;
end

function [mcaDb, referenceDb, correctionDb, residualDb, identityErrorDb] = ...
        build_spectral_tensors(mca, referenceLeft, referenceRight, ...
        frequencyMask, magnitudeFloorDb)
frequencyCount = sum(frequencyMask);
directionCount = size(referenceLeft, 1);
assert(size(mca.HRTF_L, 1) == directionCount && ...
    size(mca.HRTF_L, 2) == numel(frequencyMask), ...
    'Unexpected MCA HRTF dimensions.');
assert(isfield(mca, 'p') && isfield(mca.p, 'corrFilt_lim'), ...
    'MCA correction filter is missing.');
assert(isfield(mca.p, 'HRTF_L_ip_noMC') && ...
    isfield(mca.p, 'HRTF_R_ip_noMC'), ...
    'Pre-correction MCA HRTFs are missing.');

referenceSpectrum = cat(3, ...
    referenceLeft(:, frequencyMask).', ...
    referenceRight(:, frequencyMask).');
mcaSpectrum = cat(3, ...
    mca.HRTF_L(:, frequencyMask).', ...
    mca.HRTF_R(:, frequencyMask).');
preCorrectionSpectrum = cat(3, ...
    mca.p.HRTF_L_ip_noMC(:, frequencyMask).', ...
    mca.p.HRTF_R_ip_noMC(:, frequencyMask).');
correctionSpectrum = mca.p.corrFilt_lim(frequencyMask, :, :);

expectedSize = [frequencyCount, directionCount, 2];
assert(isequal(size(referenceSpectrum), expectedSize), ...
    'Unexpected reference tensor dimensions.');
assert(isequal(size(mcaSpectrum), expectedSize), ...
    'Unexpected MCA tensor dimensions.');
assert(isequal(size(correctionSpectrum), expectedSize), ...
    'Unexpected correction tensor dimensions.');

magnitudeFloor = 10 ^ (magnitudeFloorDb / 20);
referenceDb = single(20 * log10(max(abs(referenceSpectrum), magnitudeFloor)));
mcaDb = single(20 * log10(max(abs(mcaSpectrum), magnitudeFloor)));
correctionDb = single(20 * log10(max( ...
    abs(correctionSpectrum), magnitudeFloor)));
preCorrectionDb = single(20 * log10(max( ...
    abs(preCorrectionSpectrum), magnitudeFloor)));
residualDb = referenceDb - mcaDb;
identityErrorDb = double(max(abs( ...
    mcaDb - (preCorrectionDb + correctionDb)), [], 'all'));
assert(identityErrorDb <= 2e-4, ...
    'MCA magnitude/correction identity error is %.6g dB.', ...
    identityErrorDb);
assert(all(isfinite(referenceDb), 'all') && ...
    all(isfinite(mcaDb), 'all') && ...
    all(isfinite(correctionDb), 'all') && ...
    all(isfinite(residualDb), 'all'), ...
    'Export tensors contain non-finite values.');
end

function features = build_direction_features(grid)
azimuthDegrees = grid(:, 1);
elevationDegrees = 90 - grid(:, 2);
x = cosd(elevationDegrees) .* cosd(azimuthDegrees);
y = cosd(elevationDegrees) .* sind(azimuthDegrees);
z = sind(elevationDegrees);
features = single([azimuthDegrees.'; elevationDegrees.'; ...
    x.'; y.'; z.'; grid(:, 3).']);
end

function metadata = build_strict_ild_metadata( ...
        mca, referenceLeft, referenceRight, frequencyMask, fftOversize)
selectedBinIndices = find(frequencyMask);
outsideBinIndices = find(~frequencyMask);
mcaSelected = cat(3, ...
    mca.HRTF_L(:, frequencyMask).', ...
    mca.HRTF_R(:, frequencyMask).');
mcaOutside = cat(3, ...
    mca.HRTF_L(:, ~frequencyMask).', ...
    mca.HRTF_R(:, ~frequencyMask).');

referenceHrirLeft = real(ifft( ...
    AKsingle2bothSidedSpectrum(referenceLeft.')));
referenceHrirRight = real(ifft( ...
    AKsingle2bothSidedSpectrum(referenceRight.')));
hrirLength = size(referenceHrirLeft, 1) / fftOversize;
assert(hrirLength == round(hrirLength), ...
    'Strict ILD HRIR length is not an integer.');
hrirLength = round(hrirLength);
referenceHrirLeft = referenceHrirLeft(1:hrirLength, :);
referenceHrirRight = referenceHrirRight(1:hrirLength, :);
leftEnergy = sum(abs(referenceHrirLeft) .^ 2, 1);
rightEnergy = sum(abs(referenceHrirRight) .^ 2, 1);
referenceIldDb = 10 * log10(leftEnergy ./ rightEnergy);

metadata = struct( ...
    'mcaSelectedPhaseRad', single(angle(mcaSelected)), ...
    'mcaOutsideReal', single(real(mcaOutside)), ...
    'mcaOutsideImag', single(imag(mcaOutside)), ...
    'selectedBinIndicesZeroBased', int32(selectedBinIndices - 1), ...
    'outsideBinIndicesZeroBased', int32(outsideBinIndices - 1), ...
    'referenceIldDb', single(referenceIldDb), ...
    'singleSidedFrequencyCount', int32(numel(frequencyMask)), ...
    'hrirLength', int32(hrirLength));
assert(all(isfinite(metadata.mcaSelectedPhaseRad), 'all') && ...
    all(isfinite(metadata.mcaOutsideReal), 'all') && ...
    all(isfinite(metadata.mcaOutsideImag), 'all') && ...
    all(isfinite(metadata.referenceIldDb), 'all'), ...
    'Strict ILD metadata contains non-finite values.');
end

function write_subject_hdf5(outputFile, mcaDb, referenceDb, ...
        correctionDb, residualDb, directionFeatures, frequencyHz, ...
        subjectId, sparseOrder, splitName, headRadius, headRadiusSource, ...
        samplingRateHz, fftOversize, correctionIdentityErrorDb, strictIld)
partialFile = [outputFile '.partial'];
if isfile(partialFile)
    delete(partialFile);
end
cleanupPartial = onCleanup(@() delete_if_present(partialFile));

write_spectral_dataset(partialFile, '/mca_logmag_db', mcaDb);
write_spectral_dataset(partialFile, '/reference_logmag_db', referenceDb);
write_spectral_dataset(partialFile, '/correction_logmag_db', correctionDb);
write_spectral_dataset(partialFile, '/target_residual_db', residualDb);

h5create(partialFile, '/direction_features', size(directionFeatures), ...
    'Datatype', 'single', 'ChunkSize', [6, 128], 'Deflate', 4);
h5write(partialFile, '/direction_features', directionFeatures);
frequencyHz = single(frequencyHz(:).');
h5create(partialFile, '/frequency_hz', size(frequencyHz), ...
    'Datatype', 'single');
h5write(partialFile, '/frequency_hz', frequencyHz);

if ~isempty(fieldnames(strictIld))
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_selected_phase_rad', ...
        strictIld.mcaSelectedPhaseRad);
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_outside_real', strictIld.mcaOutsideReal);
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_outside_imag', strictIld.mcaOutsideImag);
    write_vector_dataset(partialFile, ...
        '/strict_ild/selected_bin_indices_zero_based', ...
        strictIld.selectedBinIndicesZeroBased);
    write_vector_dataset(partialFile, ...
        '/strict_ild/outside_bin_indices_zero_based', ...
        strictIld.outsideBinIndicesZeroBased);
    write_vector_dataset(partialFile, ...
        '/strict_ild/reference_ild_db', strictIld.referenceIldDb);
    h5writeatt(partialFile, '/strict_ild', ...
        'single_sided_frequency_count', ...
        strictIld.singleSidedFrequencyCount);
    h5writeatt(partialFile, '/strict_ild', ...
        'hrir_length', strictIld.hrirLength);
    h5writeatt(partialFile, '/strict_ild', 'definition', ...
        ['Corrected MCA magnitude with original MCA phase, ', ...
        'both-sided IFFT, crop to original HRIR length, ', ...
        '10*log10(left energy/right energy)']);
end

h5writeatt(partialFile, '/', 'schema_version', ...
    ternary_string(~isempty(fieldnames(strictIld)), '1.1', '1.0'));
h5writeatt(partialFile, '/', 'subject_id', int32(subjectId));
h5writeatt(partialFile, '/', 'sparse_order', int32(sparseOrder));
h5writeatt(partialFile, '/', 'split', char(splitName));
h5writeatt(partialFile, '/', 'python_spectral_layout', ...
    'ear,direction,frequency');
h5writeatt(partialFile, '/', 'ear_order', 'left,right');
h5writeatt(partialFile, '/', 'direction_feature_order', ...
    'azimuth_deg,elevation_deg,x,y,z,fliege_weight');
h5writeatt(partialFile, '/', 'target_definition', ...
    'reference_logmag_db - mca_logmag_db');
h5writeatt(partialFile, '/', 'head_radius_m', double(headRadius));
h5writeatt(partialFile, '/', 'head_radius_source', char(headRadiusSource));
h5writeatt(partialFile, '/', 'sampling_rate_hz', double(samplingRateHz));
h5writeatt(partialFile, '/', 'fft_oversize', int32(fftOversize));
h5writeatt(partialFile, '/', 'magnitude_floor_db', -200.0);
h5writeatt(partialFile, '/', 'correction_identity_max_error_db', ...
    correctionIdentityErrorDb);
h5writeatt(partialFile, '/', 'strict_ild_metadata', ...
    int32(~isempty(fieldnames(strictIld))));
h5writeatt(partialFile, '/', 'created_at', ...
    char(datetime('now', 'TimeZone', 'local')));
h5writeatt(partialFile, '/', 'complete', int32(1));

movefile(partialFile, outputFile, 'f');
clear cleanupPartial;
end

function write_spectral_dataset(file, path, values)
valueSize = size(values);
chunkSize = [min(64, valueSize(1)), min(128, valueSize(2)), 1];
h5create(file, path, valueSize, 'Datatype', 'single', ...
    'ChunkSize', chunkSize, 'Deflate', 4);
h5write(file, path, values);
end

function write_vector_dataset(file, path, values)
values = values(:).';
h5create(file, path, size(values), 'Datatype', class(values));
h5write(file, path, values);
end

function value = ternary_string(condition, whenTrue, whenFalse)
if condition
    value = whenTrue;
else
    value = whenFalse;
end
end

function complete = is_complete_hdf5(file, requireStrictIldMetadata)
complete = false;
if ~isfile(file)
    return;
end
try
    complete = h5readatt(file, '/', 'complete') == 1;
    if complete && requireStrictIldMetadata
        complete = h5readatt(file, '/', 'strict_ild_metadata') == 1;
    end
catch
    complete = false;
end
end

function delete_if_present(file)
if isfile(file)
    delete(file);
end
end

function row = make_status_row(subjectId, sparseOrder, splitName, success, ...
        outputFile, elapsedSeconds, sampleCount, residualMeanDb, ...
        residualAbsoluteMeanDb, errorMessage)
row = table(subjectId, sparseOrder, string(splitName), success, ...
    string(outputFile), elapsedSeconds, sampleCount, residualMeanDb, ...
    residualAbsoluteMeanDb, string(errorMessage), ...
    'VariableNames', {'SubjectID', 'SparseOrder', 'Split', 'Success', ...
    'OutputFile', 'ElapsedSeconds', 'SampleCount', 'ResidualMean_dB', ...
    'ResidualAbsoluteMean_dB', 'ErrorMessage'});
end

function write_failure_report(subjectId, sparseOrder, exception, subjectDir)
failure = struct( ...
    'subjectId', subjectId, ...
    'sparseOrder', sparseOrder, ...
    'message', exception.message, ...
    'identifier', exception.identifier, ...
    'stack', exception.stack, ...
    'failedAt', datetime('now', 'TimeZone', 'local'));
save(fullfile(subjectDir, sprintf( ...
    'n%02d_failure.mat', sparseOrder)), 'failure');
end

function [headRadius, source] = resolve_head_radius(anthropometry, subjectId)
subjectRow = anthropometry(anthropometry.SubjectID == subjectId, :);
assert(height(subjectRow) == 1, ...
    'Expected exactly one anthropometry row for subject %d.', subjectId);
if all(isfinite([subjectRow.x1, subjectRow.x2, subjectRow.x3]))
    headRadius = supdeq_optRadius( ...
        subjectRow.x1 / 100, subjectRow.x2 / 100, ...
        subjectRow.x3 / 100, 'Algazi');
    source = "Individual public x1/x2/x3";
    return;
end

validMask = isfinite(anthropometry.x1) & ...
    isfinite(anthropometry.x2) & isfinite(anthropometry.x3);
validRows = anthropometry(validMask, :);
validRadii = arrayfun(@(rowIndex) supdeq_optRadius( ...
    validRows.x1(rowIndex) / 100, validRows.x2(rowIndex) / 100, ...
    validRows.x3(rowIndex) / 100, 'Algazi'), ...
    (1:height(validRows)).');
headRadius = mean(validRadii);
source = sprintf( ...
    "Imputed mean Algazi radius from %d public subjects", ...
    height(validRows));
warning('HUTUBS:MissingAnthropometry', ...
    ['Subject %d has no public x1/x2/x3 values; using mean ', ...
    'Algazi radius %.6f m from %d subjects.'], ...
    subjectId, headRadius, height(validRows));
end
