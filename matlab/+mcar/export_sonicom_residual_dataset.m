function export_sonicom_residual_dataset(subjectIds, numWorkers, ...
        outputName, tikhonovEpsilon, includeStrictIldMetadata, allowTest, directionCount)
%EXPORT_SONICOM_RESIDUAL_DATASET Export SONICOM Q26 MCA residual HDF5.
%
% Defaults run one train and one validation subject:
%   subjectIds               = ["P0002", "P0001"]
%   numWorkers               = 1
%   outputName               = 'sonicom_pilot_q26_tikh1e6'
%   tikhonovEpsilon          = 1e-6
%   includeStrictIldMetadata = true
%   allowTest                = false
%
% The locked SONICOM test split is rejected unless allowTest is explicitly
% true.  The reference grid is the 793 measured directions; the sparse
% input grid is SONICOM-Q26-v1.

if nargin < 1 || isempty(subjectIds)
    subjectIds = ["P0002", "P0001"];
end
if nargin < 2 || isempty(numWorkers)
    numWorkers = 1;
end
if nargin < 3 || isempty(outputName)
    outputName = 'sonicom_pilot_q26_tikh1e6';
end
if nargin < 4 || isempty(tikhonovEpsilon)
    tikhonovEpsilon = 1e-6;
end
if nargin < 5 || isempty(includeStrictIldMetadata)
    includeStrictIldMetadata = true;
end
if nargin < 6 || isempty(allowTest)
    allowTest = false;
end
if nargin < 7 || isempty(directionCount)
    directionCount = 26;
end

subjectIds = normalize_subject_ids(subjectIds);
validateattributes(numWorkers, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1});
validateattributes(outputName, {'char', 'string'}, {'scalartext'});
validateattributes(tikhonovEpsilon, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>=', 0});
validateattributes(includeStrictIldMetadata, {'logical', 'numeric'}, ...
    {'scalar'});
validateattributes(allowTest, {'logical', 'numeric'}, {'scalar'});
validateattributes(directionCount, {'numeric'}, {'scalar', 'integer', 'positive'});
outputName = char(outputName);
includeStrictIldMetadata = logical(includeStrictIldMetadata);
allowTest = logical(allowTest);

scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
supdeqDir = fullfile(projectRoot, 'external', 'SUpDEq');
sonicomRoot = fullfile(projectRoot, 'data', 'HRTF', ...
    'sonicom_measured_ffcmp_minphase_44k1');
configDir = fullfile(projectRoot, 'configs', 'data');
splitFile = fullfile(configDir, 'sonicom_subject_split_v1.csv');
sparseGridFile = fullfile(configDir, 'sonicom_nested_sparse_grid_q14_q26_q50_v1.csv');
referenceGridFile = fullfile(configDir, ...
    'sonicom_reference_grid_v1.csv');
preparationReportFile = fullfile(configDir, ...
    'sonicom_preparation_report_v1.json');
outputRoot = fullfile(projectRoot, 'data', 'processed', outputName);
subjectsRoot = fullfile(outputRoot, 'subjects');

assert(isfolder(supdeqDir), 'SUpDEq directory not found: %s', supdeqDir);
assert(isfolder(sonicomRoot), ...
    'SONICOM directory not found: %s', sonicomRoot);
assert(isfile(splitFile), 'Split file not found: %s', splitFile);
assert(isfile(sparseGridFile), 'Sparse grid file not found: %s', sparseGridFile);
assert(isfile(referenceGridFile), ...
    'Reference grid file not found: %s', referenceGridFile);
assert(isfile(preparationReportFile), ...
    'Preparation report not found: %s', preparationReportFile);
if ~isfolder(subjectsRoot)
    mkdir(subjectsRoot);
end

splitTable = readtable(splitFile, 'TextType', 'string');
sparseGridTable = readtable(sparseGridFile, 'TextType', 'string');
q26Table = sparseGridTable(sparseGridTable.direction_count == directionCount, :);
referenceGridTable = readtable(referenceGridFile, 'TextType', 'string');
preparationReport = jsondecode(fileread(preparationReportFile));
if directionCount == 26
    validate_configs(splitTable, q26Table, referenceGridTable, preparationReport);
else
    assert(height(q26Table) == directionCount && ...
        numel(unique(q26Table.source_index_zero_based)) == directionCount, ...
        'Configured sparse grid must contain unique current-Q directions.');
    assert(height(referenceGridTable) == 793 && ...
        sum(referenceGridTable.is_interpolation_evaluation) == 767, ...
        'Reference grid dimensions are invalid.');
end

selectedSplitRows = splitTable( ...
    ismember(splitTable.subject_id, subjectIds), :);
assert(height(selectedSplitRows) == numel(subjectIds), ...
    'Every requested SONICOM subject must occur exactly once in the split.');
if ~allowTest
    testSubjects = selectedSplitRows.subject_id( ...
        selectedSplitRows.split == "test");
    assert(isempty(testSubjects), ...
        ['Locked SONICOM test subjects were requested: %s. ', ...
        'Do not set allowTest=true during development or model selection.'], ...
        strjoin(cellstr(testSubjects), ', '));
end

configuration = struct( ...
    'dataset', 'SONICOM measured clean cohort', ...
    'variant', 'FreeFieldCompMinPhase_44kHz', ...
    'subjectIds', subjectIds, ...
    'numWorkers', min(numWorkers, numel(subjectIds)), ...
    'outputName', outputName, ...
    'splitFile', splitFile, ...
    'sparseGridFile', sparseGridFile, ...
    'directionCount', directionCount, ...
    'referenceGridFile', referenceGridFile, ...
    'sparseGridName', 'SONICOM-Q26-v1', ...
    'sparseOrder', 3, ...
    'sparseDirectionCount', directionCount, ...
    'referenceDirectionCount', 793, ...
    'interpolationDirectionCount', 767, ...
    'fftOversize', 4, ...
    'frequencyMinimumHz', 50, ...
    'frequencyMaximumHz', 20000, ...
    'magnitudeFloorDb', -200, ...
    'headRadiusM', 0.09, ...
    'headRadiusSource', ...
        'SONICOM nominal ReceiverPosition; constant across subjects', ...
    'tikhonovEpsilon', tikhonovEpsilon, ...
    'mcaMaximumBoostDb', inf, ...
    'mcaMinimumPhase', true, ...
    'mcaLimitBelowSpatialAliasingFrequency', true, ...
    'mcaAliasingFade', 'fadeDown', ...
    'includeStrictIldMetadata', includeStrictIldMetadata, ...
    'allowTest', allowTest, ...
    'sourceGridSha256', ...
        preparationReport.dataset.source_grid_sha256, ...
    'matlabVersion', version, ...
    'startedAt', datetime('now', 'TimeZone', 'local'));
save(fullfile(outputRoot, 'run_configuration.mat'), 'configuration');

fprintf(['Starting SONICOM residual export: %d subjects, Q%d, ', ...
    'Tikhonov epsilon %.3g, strict ILD %d.\n'], ...
    numel(subjectIds), directionCount, tikhonovEpsilon, ...
    includeStrictIldMetadata);

statusCells = cell(numel(subjectIds), 1);
if isscalar(subjectIds) || numWorkers == 1
    initialize_worker(supdeqDir);
    for subjectIndex = 1:numel(subjectIds)
        statusCells{subjectIndex} = process_subject( ...
            subjectIds(subjectIndex), sonicomRoot, subjectsRoot, ...
            splitTable, q26Table, referenceGridTable, configuration);
    end
else
    requestedWorkers = min(numWorkers, numel(subjectIds));
    pool = gcp('nocreate');
    if isempty(pool)
        pool = parpool('local', requestedWorkers);
    elseif pool.NumWorkers ~= requestedWorkers
        delete(pool);
        pool = parpool('local', requestedWorkers);
    end
    addAttachedFiles(pool, {mfilename('fullpath')});
    workerEnvironment = parallel.pool.Constant( ...
        @() initialize_worker(supdeqDir));
    parfor subjectIndex = 1:numel(subjectIds)
        workerEnvironment.Value;
        statusCells{subjectIndex} = process_subject( ...
            subjectIds(subjectIndex), sonicomRoot, subjectsRoot, ...
            splitTable, q26Table, referenceGridTable, configuration);
    end
    delete(workerEnvironment);
end

statusTable = vertcat(statusCells{:});
writetable(statusTable, fullfile(outputRoot, 'export_status.csv'));
save(fullfile(outputRoot, 'export_status.mat'), 'statusTable');
configuration.finishedAt = datetime('now', 'TimeZone', 'local');
configuration.completedFileCount = sum(statusTable.Success);
configuration.failedFileCount = sum(~statusTable.Success);
save(fullfile(outputRoot, 'run_configuration.mat'), 'configuration');

fprintf('\nSONICOM residual export finished: %d succeeded, %d failed.\n', ...
    configuration.completedFileCount, configuration.failedFileCount);
fprintf('Output root: %s\n', outputRoot);
disp(statusTable);
end

function subjectIds = normalize_subject_ids(subjectIds)
if isnumeric(subjectIds)
    validateattributes(subjectIds, {'numeric'}, ...
        {'integer', '>=', 1, '<=', 9999, 'nonempty'});
    subjectIds = compose("P%04d", subjectIds);
else
    subjectIds = upper(string(subjectIds));
end
subjectIds = unique(subjectIds(:).', 'stable');
assert(~isempty(subjectIds), 'At least one subject is required.');
valid = ~cellfun('isempty', regexp(cellstr(subjectIds), ...
    '^P\d{4}$', 'once'));
assert(all(valid), 'Subject IDs must have form PXXXX.');
end

function validate_configs(splitTable, q26Table, referenceGridTable, report)
assert(height(splitTable) == 350, ...
    'SONICOM split must contain 350 subjects.');
assert(sum(splitTable.split == "train") == 262, ...
    'Expected 262 SONICOM training subjects.');
assert(sum(splitTable.split == "val") == 44, ...
    'Expected 44 SONICOM validation subjects.');
assert(sum(splitTable.split == "test") == 44, ...
    'Expected 44 SONICOM test subjects.');
assert(numel(unique(splitTable.subject_id)) == 350, ...
    'SONICOM split contains duplicate subjects.');
assert(height(q26Table) == 26 && ...
    numel(unique(q26Table.source_index_zero_based)) == 26, ...
    'SONICOM-Q26 must contain 26 unique source indices.');
assert(height(referenceGridTable) == 793, ...
    'SONICOM reference grid must contain 793 directions.');
assert(sum(referenceGridTable.is_q26_sparse_input) == 26, ...
    'Reference grid Q26 mask must contain 26 directions.');
assert(sum(referenceGridTable.is_interpolation_evaluation) == 767, ...
    'Reference grid interpolation mask must contain 767 directions.');
assert(abs(sum(referenceGridTable.solid_angle_weight) - 1) <= 1e-12, ...
    'Reference solid-angle weights must sum to one.');
assert(report.sonicom_q26_v1.real_sh_design_rank == 16, ...
    'Preparation report Q26 SH rank is invalid.');
assert(report.sonicom_q26_v1.real_sh_design_condition_number < 5, ...
    'Preparation report Q26 SH condition is invalid.');
end

function environment = initialize_worker(supdeqDir)
originalDir = pwd;
restoreDirectory = onCleanup(@() cd(originalDir));
cd(supdeqDir);
supdeq_start;
environment = struct('initialized', true);
clear restoreDirectory;
end

function status = process_subject(subjectId, sonicomRoot, subjectsRoot, ...
        splitTable, q26Table, referenceGridTable, config)
subjectStart = tic;
subjectDir = fullfile(subjectsRoot, char(subjectId));
if ~isfolder(subjectDir)
    mkdir(subjectDir);
end
logFile = fullfile(subjectDir, 'export.log');
diary(logFile);
stopDiary = onCleanup(@() diary('off'));
outputFile = fullfile(subjectDir, sprintf('q%d.h5', config.directionCount));

splitRow = splitTable(splitTable.subject_id == subjectId, :);
assert(height(splitRow) == 1, ...
    'Expected exactly one split row for %s.', subjectId);
splitName = splitRow.split;
sourceRelativePath = fullfile('subjects', sprintf( ...
    '%s_FreeFieldCompMinPhase_44kHz.sofa', subjectId));
sofaFile = fullfile(sonicomRoot, sourceRelativePath);
try
    if is_complete_hdf5(outputFile, config)
        fprintf('%s Q%d already complete; skipping.\n', subjectId, config.directionCount);
        status = make_status_row(subjectId, splitName, true, outputFile, ...
            NaN, NaN, NaN, NaN, config.tikhonovEpsilon, ...
            "Skipped existing complete file");
        clear stopDiary;
        return;
    end
    if isfile(outputFile)
        delete(outputFile);
    end
    assert(isfile(sofaFile), 'SONICOM SOFA not found: %s', sofaFile);
    sofa = SOFAload(sofaFile);
    assert(strcmp(sofa.GLOBAL_SOFAConventions, ...
        'SimpleFreeFieldHRIR'), ...
        'Unexpected SOFA convention: %s', ...
        sofa.GLOBAL_SOFAConventions);

    [referenceLeft, referenceRight, frequencyHz, hrirLength, ...
        sourceDistanceM] = sofa_reference_spectra( ...
        sofa, referenceGridTable, config);
    q26Indices = double(q26Table.source_index_zero_based) + 1;
    sparseGrid = [double(q26Table.azimuth_deg), ...
        double(q26Table.colatitude_deg)];
    sparseHrtf = struct( ...
        'HRTF_L', referenceLeft(q26Indices, :), ...
        'HRTF_R', referenceRight(q26Indices, :), ...
        'f', frequencyHz, ...
        'fs', double(sofa.Data.SamplingRate), ...
        'Nmax', config.sparseOrder, ...
        'FFToversize', config.fftOversize, ...
        'samplingGrid', sparseGrid, ...
        'sourceDistance', sourceDistanceM);
    referenceGrid = [double(referenceGridTable.azimuth_deg), ...
        double(referenceGridTable.colatitude_deg), ...
        double(referenceGridTable.solid_angle_weight)];

    mca = supdeq_interpHRTF( ...
        sparseHrtf, referenceGrid, 'SUpDEq', 'SH', inf, ...
        config.headRadiusM, config.tikhonovEpsilon, true, 0, ...
        true, 'fadeDown');
    frequencyMask = frequencyHz >= config.frequencyMinimumHz & ...
        frequencyHz <= config.frequencyMaximumHz;
    selectedFrequencyHz = frequencyHz(frequencyMask);
    assert(numel(selectedFrequencyHz) == 463, ...
        'Expected 463 selected frequency bins, found %d.', ...
        numel(selectedFrequencyHz));

    [mcaDb, referenceDb, correctionDb, residualDb, ...
        correctionIdentityErrorDb] = build_spectral_tensors( ...
        mca, referenceLeft, referenceRight, frequencyMask, ...
        config.magnitudeFloorDb);
    strictIld = struct();
    if config.includeStrictIldMetadata
        strictIld = build_strict_ild_metadata( ...
            mca, referenceLeft, referenceRight, frequencyMask, ...
            config.fftOversize, hrirLength);
    end
    directionFeatures = build_direction_features(referenceGridTable);
    write_subject_hdf5( ...
        outputFile, mcaDb, referenceDb, correctionDb, residualDb, ...
        directionFeatures, selectedFrequencyHz, subjectId, splitName, ...
        sourceRelativePath, double(sofa.Data.SamplingRate), ...
        q26Indices - 1, ...
        logical(referenceGridTable.is_interpolation_evaluation), ...
        config, correctionIdentityErrorDb, strictIld);

    elapsedSeconds = toc(subjectStart);
    status = make_status_row( ...
        subjectId, splitName, true, outputFile, elapsedSeconds, ...
        numel(residualDb), mean(residualDb, 'all'), ...
        mean(abs(residualDb), 'all'), config.tikhonovEpsilon, "");
    fprintf(['%s Q26 exported in %.1f s; %d samples, ', ...
        '|residual| %.4f dB.\n'], subjectId, elapsedSeconds, ...
        numel(residualDb), mean(abs(residualDb), 'all'));
catch exception
    elapsedSeconds = toc(subjectStart);
    status = make_status_row( ...
        subjectId, splitName, false, outputFile, elapsedSeconds, ...
        NaN, NaN, NaN, config.tikhonovEpsilon, ...
        string(exception.message));
    write_failure_report(subjectId, exception, subjectDir, config);
    fprintf(2, '%s Q26 failed: %s\n', subjectId, exception.message);
end
clear stopDiary;
end

function [leftSpectrum, rightSpectrum, frequencyHz, hrirLength, ...
        sourceDistanceM] = sofa_reference_spectra( ...
        sofa, referenceGridTable, config)
sourcePosition = double(sofa.SourcePosition);
assert(size(sourcePosition, 1) == 793 && ...
    size(sourcePosition, 2) >= 3, ...
    'Expected SONICOM SourcePosition [793, >=3].');
expectedAzimuth = double(referenceGridTable.azimuth_deg);
expectedElevation = double(referenceGridTable.elevation_deg);
azimuthError = abs(mod(sourcePosition(:, 1) - ...
    expectedAzimuth + 180, 360) - 180);
elevationError = abs(sourcePosition(:, 2) - expectedElevation);
assert(max(azimuthError) <= 1e-8 && ...
    max(elevationError) <= 1e-8, ...
    'SOFA SourcePosition differs from the frozen reference grid.');
assert(all(abs(sourcePosition(:, 3) - sourcePosition(1, 3)) <= 1e-12), ...
    'SONICOM source distance is not constant.');
sourceDistanceM = sourcePosition(1, 3);

hrir = double(sofa.Data.IR);
assert(isequal(size(hrir), [793, 2, 256]), ...
    'Expected Data.IR [793, 2, 256], got %s.', ...
    mat2str(size(hrir)));
samplingRateHz = double(sofa.Data.SamplingRate);
assert(isscalar(samplingRateHz) && samplingRateHz == 44100, ...
    'Expected a 44.1 kHz scalar sampling rate.');
hrirLength = size(hrir, 3);
nfft = 2 ^ nextpow2(hrirLength) * config.fftOversize;
assert(nfft == 1024, 'Expected a 1024-point FFT.');
leftHrir = squeeze(hrir(:, 1, :)).';
rightHrir = squeeze(hrir(:, 2, :)).';
leftFft = fft(leftHrir, nfft, 1);
rightFft = fft(rightHrir, nfft, 1);
singleSidedCount = nfft / 2 + 1;
leftSpectrum = leftFft(1:singleSidedCount, :).';
rightSpectrum = rightFft(1:singleSidedCount, :).';
frequencyHz = (0:(singleSidedCount - 1)).' * samplingRateHz / nfft;
assert(all(isfinite(leftSpectrum), 'all') && ...
    all(isfinite(rightSpectrum), 'all'), ...
    'Reference spectra contain non-finite values.');
end

function [mcaDb, referenceDb, correctionDb, residualDb, identityErrorDb] = ...
        build_spectral_tensors(mca, referenceLeft, referenceRight, ...
        frequencyMask, magnitudeFloorDb)
frequencyCount = sum(frequencyMask);
directionCount = size(referenceLeft, 1);
assert(size(mca.HRTF_L, 1) == directionCount && ...
    size(mca.HRTF_L, 2) == numel(frequencyMask), ...
    'Unexpected MCA HRTF dimensions.');
assert(isfield(mca, 'p') && isfield(mca.p, 'corrFilt_lim'), ...
    'MCA correction filter is missing.');
assert(isfield(mca.p, 'HRTF_L_ip_noMC') && ...
    isfield(mca.p, 'HRTF_R_ip_noMC'), ...
    'Pre-correction MCA HRTFs are missing.');

referenceSpectrum = cat(3, ...
    referenceLeft(:, frequencyMask).', ...
    referenceRight(:, frequencyMask).');
mcaSpectrum = cat(3, ...
    mca.HRTF_L(:, frequencyMask).', ...
    mca.HRTF_R(:, frequencyMask).');
preCorrectionSpectrum = cat(3, ...
    mca.p.HRTF_L_ip_noMC(:, frequencyMask).', ...
    mca.p.HRTF_R_ip_noMC(:, frequencyMask).');
correctionSpectrum = mca.p.corrFilt_lim(frequencyMask, :, :);
expectedSize = [frequencyCount, directionCount, 2];
assert(isequal(size(referenceSpectrum), expectedSize), ...
    'Unexpected reference tensor dimensions.');
assert(isequal(size(mcaSpectrum), expectedSize), ...
    'Unexpected MCA tensor dimensions.');
assert(isequal(size(correctionSpectrum), expectedSize), ...
    'Unexpected correction tensor dimensions.');

magnitudeFloor = 10 ^ (magnitudeFloorDb / 20);
referenceDb = single(20 * log10(max(abs(referenceSpectrum), ...
    magnitudeFloor)));
mcaDb = single(20 * log10(max(abs(mcaSpectrum), magnitudeFloor)));
correctionDb = single(20 * log10(max(abs(correctionSpectrum), ...
    magnitudeFloor)));
preCorrectionDb = single(20 * log10(max(abs(preCorrectionSpectrum), ...
    magnitudeFloor)));
residualDb = referenceDb - mcaDb;
identityErrorDb = double(max(abs( ...
    mcaDb - (preCorrectionDb + correctionDb)), [], 'all'));
assert(identityErrorDb <= 2e-4, ...
    'MCA magnitude/correction identity error is %.6g dB.', ...
    identityErrorDb);
assert(all(isfinite(referenceDb), 'all') && ...
    all(isfinite(mcaDb), 'all') && ...
    all(isfinite(correctionDb), 'all') && ...
    all(isfinite(residualDb), 'all'), ...
    'Export tensors contain non-finite values.');
end

function features = build_direction_features(referenceGridTable)
azimuthDegrees = double(referenceGridTable.azimuth_deg);
elevationDegrees = double(referenceGridTable.elevation_deg);
x = cosd(elevationDegrees) .* cosd(azimuthDegrees);
y = cosd(elevationDegrees) .* sind(azimuthDegrees);
z = sind(elevationDegrees);
weights = double(referenceGridTable.solid_angle_weight);
features = single([azimuthDegrees.'; elevationDegrees.'; ...
    x.'; y.'; z.'; weights.']);
end

function metadata = build_strict_ild_metadata( ...
        mca, referenceLeft, referenceRight, frequencyMask, ...
        fftOversize, expectedHrirLength)
selectedBinIndices = find(frequencyMask);
outsideBinIndices = find(~frequencyMask);
mcaSelected = cat(3, ...
    mca.HRTF_L(:, frequencyMask).', ...
    mca.HRTF_R(:, frequencyMask).');
mcaOutside = cat(3, ...
    mca.HRTF_L(:, ~frequencyMask).', ...
    mca.HRTF_R(:, ~frequencyMask).');

referenceHrirLeft = real(ifft( ...
    AKsingle2bothSidedSpectrum(referenceLeft.')));
referenceHrirRight = real(ifft( ...
    AKsingle2bothSidedSpectrum(referenceRight.')));
hrirLength = size(referenceHrirLeft, 1) / fftOversize;
assert(hrirLength == expectedHrirLength, ...
    'Strict ILD HRIR length differs from the source HRIR length.');
referenceHrirLeft = referenceHrirLeft(1:hrirLength, :);
referenceHrirRight = referenceHrirRight(1:hrirLength, :);
leftEnergy = sum(abs(referenceHrirLeft) .^ 2, 1);
rightEnergy = sum(abs(referenceHrirRight) .^ 2, 1);
referenceIldDb = 10 * log10(leftEnergy ./ rightEnergy);

metadata = struct( ...
    'mcaSelectedPhaseRad', single(angle(mcaSelected)), ...
    'mcaOutsideReal', single(real(mcaOutside)), ...
    'mcaOutsideImag', single(imag(mcaOutside)), ...
    'selectedBinIndicesZeroBased', int32(selectedBinIndices - 1), ...
    'outsideBinIndicesZeroBased', int32(outsideBinIndices - 1), ...
    'referenceIldDb', single(referenceIldDb), ...
    'singleSidedFrequencyCount', int32(numel(frequencyMask)), ...
    'hrirLength', int32(hrirLength));
assert(all(isfinite(metadata.mcaSelectedPhaseRad), 'all') && ...
    all(isfinite(metadata.mcaOutsideReal), 'all') && ...
    all(isfinite(metadata.mcaOutsideImag), 'all') && ...
    all(isfinite(metadata.referenceIldDb), 'all'), ...
    'Strict ILD metadata contains non-finite values.');
end

function write_subject_hdf5(outputFile, mcaDb, referenceDb, ...
        correctionDb, residualDb, directionFeatures, frequencyHz, ...
        subjectId, splitName, sourceRelativePath, samplingRateHz, ...
        sparseIndicesZeroBased, interpolationMask, config, ...
        correctionIdentityErrorDb, strictIld)
partialFile = [outputFile '.partial'];
if isfile(partialFile)
    delete(partialFile);
end
cleanupPartial = onCleanup(@() delete_if_present(partialFile));

write_spectral_dataset(partialFile, '/mca_logmag_db', mcaDb);
write_spectral_dataset(partialFile, '/reference_logmag_db', referenceDb);
write_spectral_dataset(partialFile, '/correction_logmag_db', ...
    correctionDb);
write_spectral_dataset(partialFile, '/target_residual_db', residualDb);
h5create(partialFile, '/direction_features', size(directionFeatures), ...
    'Datatype', 'single', 'ChunkSize', [6, 128], 'Deflate', 4);
h5write(partialFile, '/direction_features', directionFeatures);
frequencyHz = single(frequencyHz(:).');
h5create(partialFile, '/frequency_hz', size(frequencyHz), ...
    'Datatype', 'single');
h5write(partialFile, '/frequency_hz', frequencyHz);
write_vector_dataset(partialFile, ...
    '/sparse_direction_indices_zero_based', ...
    int32(sparseIndicesZeroBased));
write_vector_dataset(partialFile, ...
    '/interpolation_evaluation_mask', uint8(interpolationMask));

if ~isempty(fieldnames(strictIld))
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_selected_phase_rad', ...
        strictIld.mcaSelectedPhaseRad);
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_outside_real', strictIld.mcaOutsideReal);
    write_spectral_dataset(partialFile, ...
        '/strict_ild/mca_outside_imag', strictIld.mcaOutsideImag);
    write_vector_dataset(partialFile, ...
        '/strict_ild/selected_bin_indices_zero_based', ...
        strictIld.selectedBinIndicesZeroBased);
    write_vector_dataset(partialFile, ...
        '/strict_ild/outside_bin_indices_zero_based', ...
        strictIld.outsideBinIndicesZeroBased);
    write_vector_dataset(partialFile, ...
        '/strict_ild/reference_ild_db', strictIld.referenceIldDb);
    h5writeatt(partialFile, '/strict_ild', ...
        'single_sided_frequency_count', ...
        strictIld.singleSidedFrequencyCount);
    h5writeatt(partialFile, '/strict_ild', ...
        'hrir_length', strictIld.hrirLength);
    h5writeatt(partialFile, '/strict_ild', 'definition', ...
        ['Corrected MCA magnitude with original MCA phase, ', ...
        'both-sided IFFT, crop to original HRIR length, ', ...
        '10*log10(left energy/right energy)']);
end

subjectNumber = int32(str2double(extractAfter(subjectId, 1)));
h5writeatt(partialFile, '/', 'schema_version', '2.0');
h5writeatt(partialFile, '/', 'dataset_name', ...
    'SONICOM measured clean cohort');
h5writeatt(partialFile, '/', 'dataset_variant', ...
    'FreeFieldCompMinPhase_44kHz');
h5writeatt(partialFile, '/', 'subject_id', subjectNumber);
h5writeatt(partialFile, '/', 'subject_label', char(subjectId));
h5writeatt(partialFile, '/', 'split', char(splitName));
h5writeatt(partialFile, '/', 'source_sofa_relative_path', ...
    sourceRelativePath);
