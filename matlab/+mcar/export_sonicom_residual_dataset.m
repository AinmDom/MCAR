function write_spectral_dataset(file, path, values)
valueSize = size(values);
chunkSize = [min(64, valueSize(1)), ...
    min(128, valueSize(2)), 1];
h5create(file, path, valueSize, 'Datatype', 'single', ...
    'ChunkSize', chunkSize, 'Deflate', 4);
h5write(file, path, values);
end

function write_vector_dataset(file, path, values)
values = values(:).';
h5create(file, path, size(values), 'Datatype', class(values));
h5write(file, path, values);
end

function complete = is_complete_hdf5(file, config)
complete = false;
if ~isfile(file)
    return;
end
try
    complete = h5readatt(file, '/', 'complete') == 1 && ...
        strcmp(h5readatt(file, '/', 'sparse_grid_name'), ...
        config.sparseGridName) && ...
        h5readatt(file, '/', 'tikhonov_epsilon') == ...
        config.tikhonovEpsilon;
    if complete && config.includeStrictIldMetadata
        complete = h5readatt(file, '/', ...
            'strict_ild_metadata') == 1;
    end
catch
    complete = false;
end
end

