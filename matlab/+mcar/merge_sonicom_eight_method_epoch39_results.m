function merge_sonicom_eight_method_epoch39_results()
%MERGE_SONICOM_EIGHT_METHOD_EPOCH39_RESULTS Add frozen FSP-AE to epoch-39 results.
%
% This is a result-level merge. It deliberately reuses the already computed
% FSP-AE subject metrics and never reads SONICOM HRTFs or model predictions.
% All statistics involving MCAR are recomputed against the paper model,
% MCAR v3.2 epoch 39.

scriptDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(fileparts(scriptDir));
sevenRoot = fullfile(projectRoot, 'results', ...
    'sonicom_seven_method_q26_epoch39_final_test');
fspRoot = fullfile(projectRoot, 'results', ...
    'sonicom_fsp_ae_q26_locked_final_test');
outputRoot = fullfile(projectRoot, 'results', ...
    'sonicom_eight_method_q26_epoch39_final_test');
figuresRoot = fullfile(outputRoot, 'figures');

assert(isfolder(sevenRoot) && isfolder(fspRoot), ...
    'A required source-result directory is missing.');
if ~isfolder(figuresRoot)
    mkdir(figuresRoot);
end

sevenLong = readtable(fullfile(sevenRoot, 'metric_long.csv'), ...
    TextType='string');
fspSourceLong = readtable(fullfile(fspRoot, 'metric_long.csv'), ...
    TextType='string');
sevenQuality = readtable(fullfile(sevenRoot, 'quality_checks.csv'), ...
    TextType='string');
fspQuality = readtable(fullfile(fspRoot, 'quality_checks.csv'), ...
    TextType='string');

methodIds = ["SHOnly" "SUpDEqSH" "SUpDEqNN" "SUpDEqBary" ...
    "MCA" "RANF" "MCARv32" "FSPAE"];
methodLabels = ["SH only" "SUpDEq + SH" ...
    "SUpDEq + Natural Neighbor" "SUpDEq + Barycentric" ...
    "MCA" "RANF" "MCAR v3.2 epoch 39" "FSP-AE"];
metricIds = ["FullSphereERB" "Contralateral25ERB" ...
    "ContralateralHighFrequency" "HorizontalILDMAE"];
paperMetricNames = ["MeasuredDomainERB" "Contralateral25ERB" ...
    "ContralateralHemisphereHF" "HorizontalILDMAE"];

assert(height(sevenLong) == 44 * 7 * 4, ...
    'The seven-method source must contain 44 x 7 x 4 rows.');
assert(all(isfinite(sevenLong.Value_dB)), ...
    'The seven-method source contains nonfinite metrics.');
assert(numel(unique(sevenLong.SubjectLabel)) == 44, ...
    'The seven-method source must contain 44 subjects.');
assert_no_duplicate_keys(sevenLong);

fspLong = fspSourceLong(fspSourceLong.Method == "FSPAE", :);
assert(height(fspLong) == 44 * 4, ...
    'The FSP-AE source must contain 44 x 4 rows.');
assert(all(isfinite(fspLong.Value_dB)), ...
    'The FSP-AE source contains nonfinite metrics.');
assert_no_duplicate_keys(fspLong);
fspLong.MethodLabel(:) = "FSP-AE";

commonMethodIds = ["SHOnly" "SUpDEqSH" "SUpDEqNN" ...
    "SUpDEqBary" "MCA" "RANF"];
commonSeven = sevenLong(ismember(sevenLong.Method, commonMethodIds), :);
commonFsp = fspSourceLong(ismember(fspSourceLong.Method, commonMethodIds), :);
commonSeven = sortrows(commonSeven, ["SubjectLabel" "Method" "Metric"]);
commonFsp = sortrows(commonFsp, ["SubjectLabel" "Method" "Metric"]);
assert(isequal(commonSeven(:, ["SubjectLabel" "SubjectID" "Method" "Metric"]), ...
    commonFsp(:, ["SubjectLabel" "SubjectID" "Method" "Metric"])), ...
    'The two source results do not have identical common keys.');
commonMaxAbsDifference = max(abs(commonSeven.Value_dB - commonFsp.Value_dB));
assert(commonMaxAbsDifference == 0, ...
    'Common non-MCAR metrics differ between source results.');

sevenSubjects = sortrows(unique(sevenLong(:, ["SubjectLabel" "SubjectID"])), ...
    "SubjectID");
fspSubjects = sortrows(unique(fspLong(:, ["SubjectLabel" "SubjectID"])), ...
    "SubjectID");
assert(isequal(sevenSubjects, fspSubjects), ...
    'FSP-AE subjects are not identical to epoch-39 subjects.');

metricLong = [sevenLong; fspLong];
[presentMethod, methodOrder] = ismember(metricLong.Method, methodIds);
[presentMetric, metricOrder] = ismember(metricLong.Metric, metricIds);
assert(all(presentMethod) && all(presentMetric), 'Unexpected method or metric ID.');
metricLong.MethodOrder = methodOrder;
metricLong.MetricOrder = metricOrder;
metricLong = sortrows(metricLong, ["SubjectID" "MethodOrder" "MetricOrder"]);
metricLong(:, ["MethodOrder" "MetricOrder"]) = [];
assert(height(metricLong) == 44 * 8 * 4, ...
    'Eight-method long table must contain 44 x 8 x 4 rows.');
assert_no_duplicate_keys(metricLong);

perSubject = make_per_subject_table(metricLong, sevenSubjects, ...
    methodIds, metricIds);
aggregate = aggregate_metrics(metricLong, methodIds, methodLabels, metricIds);
paperTable = make_paper_table(aggregate, methodIds, methodLabels, metricIds);
paperLabelTable = make_paper_table(aggregate, methodIds, methodLabels, ...
    metricIds, paperMetricNames);
ranking = make_ranking_table(aggregate, metricIds, paperMetricNames);
paired = paired_bootstrap(metricLong, ...
    ["MCA" "RANF" "FSPAE"], metricIds, paperMetricNames, 100000, 20260813);

qualityChecks = merge_quality_checks(sevenQuality, fspQuality);
assert(height(qualityChecks) == 44, 'Quality-check row count must be 44.');
assert(all(qualityChecks.FSPAEFrequencyMaxAbsError_Hz == 0), ...
    'FSP-AE frequency-grid error is not zero.');

writetable(metricLong, fullfile(outputRoot, 'metric_long.csv'));
writetable(perSubject, fullfile(outputRoot, 'per_subject_metrics.csv'));
writetable(qualityChecks, fullfile(outputRoot, 'quality_checks.csv'));
writetable(aggregate, fullfile(outputRoot, 'aggregate_metrics.csv'));
writetable(paperTable, fullfile(outputRoot, 'paper_comparison.csv'));
writetable(paperLabelTable, fullfile(outputRoot, ...
    'paper_comparison_paper_labels.csv'));
writetable(ranking, fullfile(outputRoot, 'metric_ranking.csv'));
writetable(paired, fullfile(outputRoot, ...
    'paired_comparison_mcar_epoch39.csv'));

plot_aggregate(aggregate, methodIds, methodLabels, metricIds, figuresRoot);
write_readme(fullfile(outputRoot, 'README.md'), paperLabelTable, paired, ...
    commonMaxAbsDifference);

configuration = struct( ...
    'schema_version', '1.0', ...
    'created_on', char(datetime('now', TimeZone='local')), ...
    'merge_type', 'result-level merge of frozen subject metrics', ...
    'split', 'test', ...
    'test_subject_count_read_during_merge', 0, ...
    'subject_count', 44, ...
    'sparse_grid', 'SONICOM-Q26-v1', ...
    'sparse_direction_count', 26, ...
    'evaluation_direction_count', 767, ...
    'seven_method_source', ...
        'results/sonicom_seven_method_q26_epoch39_final_test', ...
    'fsp_ae_source', ...
        'results/sonicom_fsp_ae_q26_locked_final_test', ...
    'mcar_model', 'MCAR v3.2 epoch 39', ...
    'fsp_ae_model', 'FSP-AE-Q26 adaptation epoch 40', ...
    'common_non_mcar_max_abs_difference_db', commonMaxAbsDifference, ...
    'bootstrap_repetitions', 100000, ...
    'bootstrap_seed', 20260813, ...
    'methods', {cellstr(methodLabels)}, ...
    'metrics', {cellstr(paperMetricNames)});
summary = struct( ...
    'schema_version', '1.0', ...
    'status', 'completed', ...
    'split', 'test', ...
    'test_subject_count_read', 0, ...
    'subject_count', 44, ...
    'method_count', 8, ...
    'metric_count', 4, ...
    'metric_long_row_count', height(metricLong), ...
    'nonfinite_metric_count', sum(~isfinite(metricLong.Value_dB)), ...
    'aggregate', table2struct(aggregate), ...
    'ranking', table2struct(ranking), ...
    'paired_comparison', table2struct(paired), ...
    'configuration', configuration);
write_json(fullfile(outputRoot, 'summary.json'), summary);

fprintf('Eight-method epoch-39 result merge completed: %s\n', outputRoot);
disp(paperLabelTable);
end

function assert_no_duplicate_keys(data)
keys = data(:, ["SubjectLabel" "Method" "Metric"]);
assert(height(unique(keys, 'rows')) == height(keys), ...
    'Duplicate subject-method-metric keys detected.');
end

function perSubject = make_per_subject_table(metricLong, subjects, ...
        methodIds, metricIds)
perSubject = subjects;
for methodId = methodIds
    for metricId = metricIds
        rows = metricLong(metricLong.Method == methodId & ...
            metricLong.Metric == metricId, ...
            ["SubjectLabel" "SubjectID" "Value_dB"]);
        rows = sortrows(rows, "SubjectID");
        assert(isequal(rows(:, ["SubjectLabel" "SubjectID"]), subjects), ...
            'Per-subject alignment failed for %s / %s.', methodId, metricId);
        variableName = methodId + "_" + metricId + "_dB";
        perSubject.(variableName) = rows.Value_dB;
    end
end
end

function aggregate = aggregate_metrics(metricLong, methodIds, methodLabels, metricIds)
aggregate = table();
for metricId = metricIds
    mca = sorted_metric_values(metricLong, "MCA", metricId);
    mcar = sorted_metric_values(metricLong, "MCARv32", metricId);
    for methodIndex = 1:numel(methodIds)
        values = sorted_metric_values(metricLong, methodIds(methodIndex), metricId);
        row = table(methodIds(methodIndex), methodLabels(methodIndex), metricId, ...
            numel(values), mean(values), std(values, 0), median(values), ...
            100 * (mean(mca) - mean(values)) / mean(mca), ...
            100 * (mean(values) - mean(mcar)) / mean(values), ...
            sum(values < mca), sum(mcar < values), ...
            VariableNames={'Method', 'MethodLabel', 'Metric', 'SubjectCount', ...
            'Mean_dB', 'Std_dB', 'Median_dB', 'ImprovementVsMCA_percent', ...
            'MCARImprovementVsMethod_percent', 'ImprovedVsMCA_SubjectCount', ...
            'MCARBetter_SubjectCount'});
        aggregate = [aggregate; row]; %#ok<AGROW>
    end
end
end

function values = sorted_metric_values(metricLong, methodId, metricId)
rows = metricLong(metricLong.Method == methodId & metricLong.Metric == metricId, ...
    ["SubjectID" "Value_dB"]);
rows = sortrows(rows, "SubjectID");
assert(height(rows) == 44, 'Expected 44 values for %s / %s.', methodId, metricId);
values = rows.Value_dB;
end

function paperTable = make_paper_table(aggregate, methodIds, methodLabels, ...
        metricIds, outputMetricNames)
if nargin < 5
    outputMetricNames = metricIds;
end
paperTable = table(methodIds.', methodLabels.', ...
    VariableNames={'Method', 'MethodLabel'});
for metricIndex = 1:numel(metricIds)
    means = zeros(numel(methodIds), 1);
    stds = zeros(numel(methodIds), 1);
    formatted = strings(numel(methodIds), 1);
    for methodIndex = 1:numel(methodIds)
        row = aggregate(aggregate.Method == methodIds(methodIndex) & ...
            aggregate.Metric == metricIds(metricIndex), :);
        means(methodIndex) = row.Mean_dB;
        stds(methodIndex) = row.Std_dB;
        formatted(methodIndex) = sprintf('%.3f +/- %.3f', ...
            row.Mean_dB, row.Std_dB);
    end
    prefix = outputMetricNames(metricIndex);
    paperTable.(prefix + "_Mean_dB") = means;
    paperTable.(prefix + "_Std_dB") = stds;
    paperTable.(prefix + "_MeanPlusMinusStd_dB") = formatted;
end
end

function ranking = make_ranking_table(aggregate, metricIds, paperMetricNames)
ranking = table();
for metricIndex = 1:numel(metricIds)
    rows = aggregate(aggregate.Metric == metricIds(metricIndex), ...
        ["Method" "MethodLabel" "Mean_dB" "Std_dB"]);
    rows = sortrows(rows, "Mean_dB", "ascend");
    block = table(repmat(paperMetricNames(metricIndex), height(rows), 1), ...
        (1:height(rows)).', rows.Method, rows.MethodLabel, rows.Mean_dB, rows.Std_dB, ...
        VariableNames={'Metric', 'Rank', 'Method', 'MethodLabel', ...
        'Mean_dB', 'Std_dB'});
    ranking = [ranking; block]; %#ok<AGROW>
end
end

function paired = paired_bootstrap(metricLong, baselineIds, metricIds, ...
        paperMetricNames, repetitions, seed)
rng(seed, 'twister');
paired = table();
for baselineId = baselineIds
    for metricIndex = 1:numel(metricIds)
        baseline = sorted_metric_values(metricLong, baselineId, metricIds(metricIndex));
        mcar = sorted_metric_values(metricLong, "MCARv32", metricIds(metricIndex));
        differences = baseline - mcar;
        sampleIndices = randi(numel(differences), numel(differences), repetitions);
        bootstrapMeans = mean(differences(sampleIndices), 1);
        interval = prctile(bootstrapMeans, [2.5 97.5]);
        row = table(baselineId, paperMetricNames(metricIndex), numel(baseline), ...
            mean(baseline), mean(mcar), mean(differences), interval(1), interval(2), ...
            sum(mcar < baseline), 100 * mean(differences) / mean(baseline), ...
            VariableNames={'Baseline', 'Metric', 'SubjectCount', ...
            'BaselineMean_dB', 'MCARv32Epoch39Mean_dB', ...
            'BaselineMinusMCARMean_dB', 'Bootstrap95Lower_dB', ...
            'Bootstrap95Upper_dB', 'MCARBetterSubjectCount', ...
            'MCARImprovement_percent'});
        paired = [paired; row]; %#ok<AGROW>
    end
end
end

function quality = merge_quality_checks(sevenQuality, fspQuality)
quality = sortrows(sevenQuality, "SubjectID");
fspQuality = sortrows(fspQuality, "SubjectID");
assert(isequal(quality(:, ["SubjectLabel" "SubjectID"]), ...
    fspQuality(:, ["SubjectLabel" "SubjectID"])), ...
    'Quality-check subject alignment failed.');
quality.FSPAEFrequencyMaxAbsError_Hz = ...
    fspQuality.FSPAEFrequencyMaxAbsError_Hz;
end

function plot_aggregate(aggregate, methodIds, methodLabels, metricIds, figuresRoot)
values = zeros(numel(metricIds), numel(methodIds));
for metricIndex = 1:numel(metricIds)
    for methodIndex = 1:numel(methodIds)
        row = aggregate(aggregate.Method == methodIds(methodIndex) & ...
            aggregate.Metric == metricIds(metricIndex), :);
        values(metricIndex, methodIndex) = row.Mean_dB;
    end
end
figureHandle = figure(Visible='off', Color='w', Position=[100 100 1700 800]);
bars = bar(values);
colors = [ ...
    0.1216 0.4667 0.7059; ... % SH only
    1.0000 0.4980 0.0549; ... % SUpDEq + SH
    1.0000 0.7333 0.0000; ... % SUpDEq + Natural Neighbor
    0.4941 0.1843 0.5569; ... % SUpDEq + Barycentric
    0.1725 0.6275 0.1725; ... % MCA
    0.0902 0.7451 0.8118; ... % RANF
    0.8392 0.1529 0.4863; ... % MCAR
    0.4039 0.2275 0.7176];    % FSP-AE
for methodIndex = 1:numel(bars)
    bars(methodIndex).FaceColor = colors(methodIndex, :);
end
grid on;
xticks(1:numel(metricIds));
xticklabels(["Measured-domain ERB" "Contra-25 ERB" ...
    "Contra-hemisphere HF" "Horizontal ILD"]);
ylabel('Mean error (dB)');
legend(methodLabels, Location='northoutside', NumColumns=4, Interpreter='none');
title('SONICOM Q26 test eight-method comparison (N=44)');
exportgraphics(figureHandle, fullfile(figuresRoot, ...
    'test44_aggregate_baselines.png'), Resolution=220);
close(figureHandle);
end

function write_readme(path, paperTable, paired, commonDifference)
file = fopen(path, 'w');
assert(file ~= -1, 'Could not open README: %s', path);
cleanup = onCleanup(@() fclose(file));
fprintf(file, '# SONICOM Q26 eight-method test comparison\n\n');
fprintf(file, '- Subjects: 44 locked test subjects\n');
fprintf(file, '- Input/evaluation directions: 26 / 767 (inputs excluded)\n');
fprintf(file, '- MCAR paper model: v3.2 epoch 39\n');
fprintf(file, '- FSP-AE: frozen Q26 adaptation, epoch 40\n');
fprintf(file, '- Merge-time test/model-prediction reads: 0\n');
fprintf(file, '- Common-method maximum source difference: %.3g dB\n\n', ...
    commonDifference);
fprintf(file, '| Method | Measured ERB | Contra25 ERB | Contra HF | Horizontal ILD |\n');
fprintf(file, '|---|---:|---:|---:|---:|\n');
for index = 1:height(paperTable)
    fprintf(file, '| %s | %s | %s | %s | %s |\n', ...
        paperTable.MethodLabel(index), ...
        paperTable.MeasuredDomainERB_MeanPlusMinusStd_dB(index), ...
        paperTable.Contralateral25ERB_MeanPlusMinusStd_dB(index), ...
        paperTable.ContralateralHemisphereHF_MeanPlusMinusStd_dB(index), ...
        paperTable.HorizontalILDMAE_MeanPlusMinusStd_dB(index));
end
fprintf(file, '\nValues are mean +/- subject standard deviation in dB; lower is better.\n\n');
fprintf(file, '## FSP-AE versus MCAR v3.2 epoch 39\n\n');
fspRows = paired(paired.Baseline == "FSPAE", :);
for index = 1:height(fspRows)
    fprintf(file, '- %s: FSP-AE minus MCAR %.4f dB, 95%% bootstrap CI [%.4f, %.4f] dB; MCAR better for %d/44 subjects.\n', ...
        fspRows.Metric(index), fspRows.BaselineMinusMCARMean_dB(index), ...
        fspRows.Bootstrap95Lower_dB(index), ...
        fspRows.Bootstrap95Upper_dB(index), ...
        fspRows.MCARBetterSubjectCount(index));
end
fprintf(file, '\nFSP-AE is the best method on contralateral-hemisphere high-frequency error. ');
fprintf(file, 'MCAR is best on the other three reported metrics.\n');
clear cleanup;
end

function write_json(path, value)
text = jsonencode(value, PrettyPrint=true);
file = fopen(path, 'w');
assert(file ~= -1, 'Could not open JSON output: %s', path);
cleanup = onCleanup(@() fclose(file));
fprintf(file, '%s\n', text);
clear cleanup;
end
